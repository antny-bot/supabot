import os
from cryptography.fernet import Fernet, InvalidToken

ENC_PREFIX = "enc:v1:"


def is_encrypted_secret(value: any) -> bool:
    return isinstance(value, str) and value.startswith(ENC_PREFIX)


def has_secret_key() -> bool:
    return bool(os.getenv("USER_SECRET_KEY", "").strip())


def _fernet() -> Fernet:
    key = os.getenv("USER_SECRET_KEY", "").strip()
    if not key:
        raise ValueError("USER_SECRET_KEY is required to encrypt user secrets")
    try:
        return Fernet(key.encode())
    except Exception as exc:
        raise ValueError("USER_SECRET_KEY must be a valid Fernet key generated by Fernet.generate_key()") from exc


def can_decrypt_secrets() -> bool:
    if not has_secret_key():
        return False
    try:
        _fernet()
        return True
    except ValueError:
        return False


def encrypt_secret(value: any) -> str:
    text = str(value or "").strip()
    if not text or is_encrypted_secret(text):
        return text
    token = _fernet().encrypt(text.encode()).decode()
    return f"{ENC_PREFIX}{token}"


def decrypt_secret(value: any) -> str:
    text = str(value or "")
    if not text or not is_encrypted_secret(text):
        return text
    try:
        return _fernet().decrypt(text[len(ENC_PREFIX):].encode()).decode()
    except (InvalidToken, Exception) as exc:
        raise ValueError("Failed to decrypt secret with current USER_SECRET_KEY") from exc
